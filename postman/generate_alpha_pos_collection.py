def route_auth(edition: str, path: str) -> tuple[str, list[dict[str, str]]]:
    """Return a human-readable auth contract and concrete Postman headers."""
    route = path.rstrip("/")
    if route == "/healthz" or route.endswith("/auth-login"):
        return "Public", []
    if route in {
        "/auth-login",
        "/auth/courier/login",
        "/auth/courier/refresh",
        "/auth/courier/revoke",
        "/payments/webhook",
        "/api/smartfood/auth",
        "/api/licensing/status",
        "/api/licensing/setup",
        "/api/licensing/plans",
        "/api/sync/health",
        "/cashiers",
    } or route.startswith("/api/qr/"):
        if route == "/payments/webhook":
            return (
                "Courier payment webhook shared secret",
                [{"key": "X-Webhook-Secret", "value": "{{paymentWebhookSecret}}"}],
            )
        return "Public", []
    if route == "/api/customer-bot/webhook":
        return (
            "Telegram webhook secret",
            [
                {
                    "key": "X-Telegram-Bot-Api-Secret-Token",
                    "value": "{{telegramWebhookSecret}}",
                }
            ],
        )
    if route.startswith("/api/sync/"):
        if route in {"/api/sync/receive", "/api/sync/changes", "/api/sync/shift-close/ack"}:
            note = "Branch credential and branch identity"
            headers = [
                {"key": "Authorization", "value": "Branch {{branchToken}}"},
                {"key": "X-Branch-ID", "value": "{{branchId}}"},
            ]
            if edition == "local" and route == "/api/sync/receive":
                note = "Cloud credential when the cloud pushes changes to local"
                headers[0]["value"] = "Cloud {{cloudSyncToken}}"
            return note, headers
        return (
            "Management credential",
            [{"key": "Authorization", "value": "Management {{managementToken}}"}],
        )
    if route.startswith("/api/smartfood/"):
        return (
            "SmartFood customer bearer token",
            [{"key": "Authorization", "value": "Bearer {{customerToken}}"}],
        )
    if (
        route.startswith("/auth/courier/")
        or route.startswith("/courier/")
        or route.startswith("/payments/")
        or (
            edition == "cloud"
            and re.fullmatch(r"/orders/:[^/]+/(accept|decline|status)", route)
        )
        or (
            edition == "local"
            and path.endswith("/")
            and re.fullmatch(r"/orders/:[^/]+/(accept|decline|status)", route)
        )
    ):
        return (
            "Courier bearer token",
            [{"key": "Authorization", "value": "Bearer {{courierToken}}"}],
        )
    if edition == "cloud":
        return (
            "Cloud administrator bearer token",
            [{"key": "Authorization", "value": "Bearer {{adminToken}}"}],
        )
    if route.startswith("/api/waiters/"):
        return (
            "Waiter bearer token",
            [{"key": "Authorization", "value": "Bearer {{waiterToken}}"}],
        )
    return (
        "Local POS bearer token",
        [{"key": "Authorization", "value": "Bearer {{posToken}}"}],
    )


