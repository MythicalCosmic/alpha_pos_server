def flatten(items: Iterable[dict[str, Any]]) -> list[dict[str, Any]]:
    """Return every Postman request item below an arbitrary folder tree."""
    result: list[dict[str, Any]] = []
    for item in items:
        if "request" in item:
            result.append(item)
        result.extend(flatten(item.get("item", [])))
    return result


def raw_url(item: dict[str, Any]) -> str:
    value = item["request"]["url"]
    return value["raw"] if isinstance(value, dict) else value


def source_path(url: str) -> str:
    return url.replace("{{base_url}}", "").split("?", 1)[0]


def source_groups(
    edition: str, source: dict[str, Any]
) -> OrderedDict[str, list[dict[str, Any]]]:
    """Group generated requests while restoring two slash-sensitive aliases.

    Django's resolver distinguishes these registered paths, but the shared raw
    generator normalizes away their trailing slash. Preserve the actual URLconf
    contract here so the final collection remains path-complete.
    """
    grouped: OrderedDict[str, list[dict[str, Any]]] = OrderedDict()
    for item in flatten(source["item"]):
        grouped.setdefault(source_path(raw_url(item)), []).append(item)

    if edition == "cloud":
        alias = "/api/admins/analytics/comparison"
        candidates = grouped.get(alias, [])
        if len(candidates) == 2 and all(
            item["request"]["method"] == "GET" for item in candidates
        ):
            grouped[alias] = [candidates[0]]
            grouped[alias + "/"] = [candidates[1]]
    else:
        alias = "/orders/:order_id/status"
        candidates = grouped.get(alias, [])
        by_method = {item["request"]["method"]: item for item in candidates}
        if {"PATCH", "POST"}.issubset(by_method):
            grouped[alias] = [by_method["PATCH"]]
            grouped[alias + "/"] = [by_method["POST"]]

    exact: OrderedDict[str, list[dict[str, Any]]] = OrderedDict()
    for path, items in grouped.items():
        restored = restore_trailing_slash(edition, path)
        if restored in exact:
            raise ValueError(
                f"slash restoration collided for {edition}: {path} -> {restored}"
            )
        exact[restored] = items
    return exact


def restore_trailing_slash(edition: str, path: str) -> str:
    """Restore exact slash style that the raw generator intentionally trims."""
    if path.endswith("/"):
        return path
    if edition == "cloud":
        if path.startswith(
            (
                "/api/admins/stock/",
                "/api/admins/hr/",
                "/api/admins/discounts/",
                "/api/admins/notifications/",
                "/api/admins/cashbox/",
                "/auth/courier/",
                "/courier/",
                "/orders/",
                "/payments/",
            )
        ):
            return path + "/"
        if path in {"/api/customer-bot/webhook", "/api/admins/couriers"}:
            return path + "/"
        return path
    if path.startswith(
        (
            "/api/cashbox/",
            "/api/qr/",
            "/auth/courier/",
            "/courier/",
            "/payments/",
        )
    ):
        return path + "/"
    if path == "/api/couriers":
        return path + "/"
    if re.fullmatch(r"/orders/:[^/]+/(accept|decline)", path):
        return path + "/"
    return path


def camel(value: str) -> str:
    parts = value.split("_")
    return parts[0] + "".join(part[:1].upper() + part[1:] for part in parts[1:])


def path_variable_name(raw_name: str, path: str) -> str:
    if raw_name == "token":
        return "qrToken"
    if raw_name == "claim_token":
        return "claimToken"
    if raw_name == "name":
        return "roleName"
    if raw_name == "kind":
        return "documentKind"
    if raw_name == "phone":
        return "phone"
    return camel(raw_name)


def postman_path(path: str) -> tuple[str, set[str]]:
    """Translate Django generator :vars into collection-scoped {{vars}}."""
    variables: set[str] = set()

    def replace(match: re.Match[str]) -> str:
        name = path_variable_name(match.group(1), path)
        variables.add(name)
        return "{{" + name + "}}"

    return re.sub(r":([A-Za-z_][A-Za-z0-9_]*)", replace, path), variables


def title_case_name(name: str) -> str:
    name = re.sub(r"\bList (?=(?:.* Detail|Me$|Settings$|Config$))", "", name)
    return name.replace("One C", "1C").replace("Ai ", "AI ")


