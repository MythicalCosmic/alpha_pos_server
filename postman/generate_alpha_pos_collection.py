def build_request(
    edition: str,
    path: str,
    source_items: list[dict[str, Any]],
    variables: set[str],
) -> dict[str, Any]:
    methods = list(OrderedDict.fromkeys(item["request"]["method"] for item in source_items))
    method = next((candidate for candidate in METHOD_PRIORITY if candidate in methods), methods[0])
    representative = next(item for item in source_items if item["request"]["method"] == method)
    display_path, discovered = postman_path(path)
    variables.update(discovered)
    base = "cloudBaseUrl" if edition == "cloud" else "localBaseUrl"
    auth_note, headers = route_auth(edition, path)
    headers = [dict(header) for header in headers]
    if path.rstrip("/") == "/api/admins/inkassa/perform":
        headers.append({"key": "Idempotency-Key", "value": "{{idempotencyKey}}"})
    body = body_example(edition, path, method)
    if body is not None:
        headers.append({"key": "Content-Type", "value": "application/json"})
    query = query_parameters(path, method)
    query_string = ""
    if query:
        query_string = "?" + "&".join(f"{key}={value}" for key, value, _ in query)
    method_list = ", ".join(methods)
    alternate = ""
    if len(methods) > 1:
        alternate = (
            "\n\nThis registered path accepts multiple methods. This item uses the "
            f"safe representative **{method}** method; supported methods: **{method_list}**. "
            "Duplicate path items are intentionally avoided."
        )
    query_doc = ""
    if query:
        query_doc = "\n\nExample query parameters:\n" + "\n".join(
            f"- `{key}` — {description}" for key, _, description in query
        )
    operational_note = ""
    if path.rstrip("/") == "/api/customer-bot/webhook":
        operational_note = (
            "\n\n**License behavior:** the mounted customer-bot webhook is explicitly "
            "allowed through license blocking so Telegram updates can still be "
            "acknowledged instead of being retried indefinitely."
        )
    description = (
        f"**Edition:** {'cloud server' if edition == 'cloud' else 'local POS'}  \n"
        f"**Registered route:** `{path}`  \n"
        f"**Authentication:** {auth_note}  \n"
        f"**Allowed methods:** {method_list}"
        f"{alternate}{query_doc}{operational_note}\n\n"
        "Replace example values and identifiers before sending a mutating request."
    )
    request: dict[str, Any] = {
        "method": method,
        "header": headers,
        "url": f"{{{{{base}}}}}{display_path}{query_string}",
        "description": description,
    }
    if body is not None:
        request["body"] = {
            "mode": "raw",
            "raw": json.dumps(body, indent=2, ensure_ascii=False),
            "options": {"raw": {"language": "json"}},
        }
    display_name = title_case_name(representative["name"])
    if edition == "cloud" and path == "/api/admins/analytics/comparison/":
        display_name += " — Trailing-Slash Alias"
    elif edition == "local" and path == "/clients/lookup":
        display_name += " — Explicit Lookup Alias"
    item: dict[str, Any] = {
        "name": f"[{method}] {display_name}",
        "request": request,
    }
    script = capture_script(edition, path, method)
    if script:
        item["event"] = [
            {
                "listen": "test",
                "script": {"type": "text/javascript", "exec": script},
            }
        ]
    return item


def insert_folder(tree: OrderedDict[str, Any], folders: list[str], item: dict[str, Any]) -> None:
    cursor = tree
    for folder in folders:
        cursor = cursor.setdefault(folder, OrderedDict())
    cursor.setdefault("__items__", []).append(item)


def materialize_tree(tree: OrderedDict[str, Any], depth: int = 0) -> list[dict[str, Any]]:
    result: list[dict[str, Any]] = []
    for name, value in tree.items():
        if name == "__items__":
            result.extend(value)
            continue
        folder: dict[str, Any] = {"name": name, "item": materialize_tree(value, depth + 1)}
        if depth == 0:
            folder["description"] = (
                "Requests are grouped by the deployed edition. HTTP routes come directly "
                "from Django's resolver; realtime routes come from the edition's ASGI router."
            )
        result.append(folder)
    return result


def websocket_item(name: str, url: str, edition: str) -> dict[str, Any]:
    auth_note = (
        "The URL includes the expected `?token=` transport because a cookie alone "
        "does not authenticate the cloud consumers."
        if edition == "cloud"
        else "The URL includes an explicit token. Local OPEN_LAN may trust the three "
        "in-store streams, but the courier stream still requires courier identity."
    )
    return {
        "name": f"[WS] {name}",
        "request": {
            "method": "GET",
            "header": [],
            "url": url,
            "description": (
                f"Registered {'cloud server' if edition == 'cloud' else 'local POS'} "
                "ASGI WebSocket route. Postman supports WebSocket requests through its "
                f"New → WebSocket flow; copy this URL there. {auth_note}"
            ),
        },
    }


def initial_variables(discovered: set[str]) -> list[dict[str, str]]:
    values = OrderedDict(BASE_VARIABLES)
    for name in sorted(discovered):
        if name in values:
            continue
        if name in ID_DEFAULTS:
            value = ID_DEFAULTS[name]
        elif name.lower().endswith("token"):
            value = ""
        elif name.lower().endswith("id"):
            value = "1"
        elif name == "roleName":
            value = "cashier"
        elif name == "documentKind":
            value = "contract"
        else:
            value = "sample"
        values[name] = value
    return [{"key": key, "value": value, "type": "string"} for key, value in values.items()]


def build_collection(server_raw: Path, local_raw: Path) -> tuple[dict[str, Any], dict[str, int]]:
    source_docs = {
        "cloud": json.loads(server_raw.read_text(encoding="utf-8")),
        "local": json.loads(local_raw.read_text(encoding="utf-8")),
    }
    tree: OrderedDict[str, Any] = OrderedDict()
    variables: set[str] = set()
    stats: dict[str, int] = {}
    for edition, source in source_docs.items():
        grouped = source_groups(edition, source)
        stats[f"{edition}_method_requests"] = sum(len(items) for items in grouped.values())
        stats[f"{edition}_distinct_paths"] = len(grouped)
        for path, source_items in grouped.items():
            folders = cloud_folders(path) if edition == "cloud" else local_folders(path)
            insert_folder(
                tree,
                folders,
                build_request(edition, path, source_items, variables),
            )
        ws_folder = ["Cloud Server" if edition == "cloud" else "Local POS", "Realtime WebSockets"]
        for name, url in WEBSOCKETS[edition]:
            insert_folder(tree, ws_folder, websocket_item(name, url, edition))
        stats[f"{edition}_websockets"] = len(WEBSOCKETS[edition])

    total_http = stats["cloud_distinct_paths"] + stats["local_distinct_paths"]
    description = f"""# Alpha POS API

Import-ready Postman Collection v2.1 for the deployed Alpha POS cloud server and
local POS editions.

## Coverage

- **{stats['cloud_distinct_paths']}** distinct cloud HTTP paths
- **{stats['local_distinct_paths']}** distinct local HTTP paths
- **{total_http}** edition/path HTTP entries in total
- **{stats['cloud_websockets']}** cloud and **{stats['local_websockets']}** local ASGI WebSocket routes

Each distinct registered HTTP path appears exactly once per deployed edition.
For multi-method Django views, the item description lists every allowed method
and the request uses one representative method. Django's generated `/admin/`
HTML application and the standalone core test URLconf are deliberately excluded.

## Safety and setup

All hosts, credentials, phone numbers, UUIDs and IDs are placeholders. No
production key or customer record is embedded. Set the collection variables for
the environment you intend to test, run the relevant login request, and inspect
every example body before sending mutations. Login/create tests only capture
authoritative token or ID fields when a successful JSON response supplies them.

## Synchronization authentication

Branch replication uses `Branch {{{{branchToken}}}}` plus `X-Branch-ID`;
cloud-to-local receive uses `Cloud {{{{cloudSyncToken}}}}`; management controls
use `Management {{{{managementToken}}}}`. Trigger, trigger-pull, full-push, and
the Cloud form of `/api/sync/receive` are local-only behavior gates; shift-close
acknowledgement is cloud-only. All eleven shared URL patterns are still
registered by both editions.
"""
    collection = {
        "info": {
            "_postman_id": str(uuid.UUID("a1fa66fb-c18d-4c13-8e3e-5481f86ddf55")),
            "name": "Alpha POS — Cloud, Local POS & Realtime API",
            "description": description,
            "schema": SCHEMA,
        },
        "variable": initial_variables(variables),
        "event": [
            {
                "listen": "test",
                "script": {
                    "type": "text/javascript",
                    "exec": [
                        "pm.test('Response is not an unhandled server error', function () {",
                        "  pm.expect(pm.response.code).to.not.eql(500);",
                        "});",
                    ],
                },
            }
        ],
        "item": materialize_tree(tree),
    }
    stats["http_total"] = total_http
    stats["websocket_total"] = stats["cloud_websockets"] + stats["local_websockets"]
    return collection, stats


def validate_coverage(
    collection: dict[str, Any], server_raw: Path, local_raw: Path
) -> list[str]:
    errors: list[str] = []
    final_items = flatten(collection["item"])
    http_items = [
        item
        for item in final_items
        if not item["name"].startswith("[WS]")
    ]
    final_by_edition: dict[str, list[str]] = {"cloud": [], "local": []}
    for item in http_items:
        url = raw_url(item)
        if url.startswith("{{cloudBaseUrl}}"):
            final_by_edition["cloud"].append(
                url.replace("{{cloudBaseUrl}}", "").split("?", 1)[0]
            )
        elif url.startswith("{{localBaseUrl}}"):
            final_by_edition["local"].append(
                url.replace("{{localBaseUrl}}", "").split("?", 1)[0]
            )
        else:
            errors.append(f"HTTP request has no edition base variable: {url}")

    for edition, raw_path in (("cloud", server_raw), ("local", local_raw)):
        source = json.loads(raw_path.read_text(encoding="utf-8"))
        expected: dict[str, set[str]] = {}
        for source_route, source_items in source_groups(edition, source).items():
            path, _ = postman_path(source_route)
            expected[path] = {
                item["request"]["method"] for item in source_items
            }
        actual = final_by_edition[edition]
        if len(actual) != len(set(actual)):
            errors.append(f"{edition}: duplicate HTTP path entries in final collection")
        missing = set(expected) - set(actual)
        extra = set(actual) - set(expected)
        if missing:
            errors.append(f"{edition}: missing paths: {sorted(missing)}")
        if extra:
            errors.append(f"{edition}: unexpected paths: {sorted(extra)}")
        base = "{{cloudBaseUrl}}" if edition == "cloud" else "{{localBaseUrl}}"
        selected = {
            raw_url(item).replace(base, "").split("?", 1)[0]: item["request"]["method"]
            for item in http_items
            if raw_url(item).startswith(base)
        }
        for path, method in selected.items():
            if path in expected and method not in expected[path]:
                errors.append(
                    f"{edition}: selected {method} is not allowed for {path}; "
                    f"expected {sorted(expected[path])}"
                )

    declared = {variable["key"] for variable in collection.get("variable", [])}
    serialized = json.dumps(collection, ensure_ascii=False)
    referenced = set(re.findall(r"\{\{([A-Za-z_][A-Za-z0-9_]*)\}\}", serialized))
    undeclared = referenced - declared
    if undeclared:
        errors.append(f"undeclared Postman variables: {sorted(undeclared)}")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--server-raw", type=Path, default=DEFAULT_SERVER_RAW)
    parser.add_argument("--local-raw", type=Path, default=DEFAULT_LOCAL_RAW)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    for source in (args.server_raw, args.local_raw):
        if not source.is_file():
            parser.error(f"missing resolver inventory: {source}")
    collection, stats = build_collection(args.server_raw, args.local_raw)
    errors = validate_coverage(collection, args.server_raw, args.local_raw)
    if errors:
        for error in errors:
            print(f"ERROR: {error}")
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(collection, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    print(
        "Wrote "
        f"{stats['http_total']} HTTP route entries and "
        f"{stats['websocket_total']} WebSocket references to {args.output}"
    )
    print(
        f"Cloud: {stats['cloud_method_requests']} method requests -> "
        f"{stats['cloud_distinct_paths']} distinct paths; "
        f"local: {stats['local_method_requests']} method requests -> "
        f"{stats['local_distinct_paths']} distinct paths."
    )
    return 0


